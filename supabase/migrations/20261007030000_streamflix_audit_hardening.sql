-- StreamFlix audit hardening: profiles, notifications, visitors, search indexes.
-- No is_featured or video_url columns are introduced.

-- Multiple profiles are a subscription feature; do not enforce one profile per user.
alter table public.profiles
  drop constraint if exists uq_profiles_user_id;

create index if not exists idx_profiles_user_id on public.profiles(user_id);

-- Stable Supabase Auth identity link. The backend derives ownership from the
-- verified auth token and this column rather than trusting a client user id.
alter table public.users
  add column if not exists auth_user_id uuid;

create unique index if not exists uq_users_auth_user_id
  on public.users(auth_user_id)
  where auth_user_id is not null;

create index if not exists idx_users_email on public.users(lower(email));

-- Persistent, user-specific application notifications.
create table if not exists public.notifications (
  notification_id bigint generated by default as identity primary key,
  user_id integer not null references public.users(user_id) on delete cascade,
  type varchar(50) not null,
  title varchar(160) not null,
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_notifications_user_created
  on public.notifications(user_id, created_at desc);

create index if not exists idx_notifications_user_unread
  on public.notifications(user_id, is_read, created_at desc);

alter table public.notifications enable row level security;

drop policy if exists notifications_owner on public.notifications;
create policy notifications_owner on public.notifications
  for all to public
  using (user_id = public.current_app_user_id())
  with check (user_id = public.current_app_user_id());

-- Lightweight visitor counting. visitor_key is an opaque server-issued value;
-- no IP address or other raw identifying data is stored.
create table if not exists public.site_visitors (
  visitor_key varchar(128) primary key,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  visit_count integer not null default 1,
  user_id integer references public.users(user_id) on delete set null
);

create index if not exists idx_site_visitors_last_seen
  on public.site_visitors(last_seen_at desc);

create index if not exists idx_site_visitors_user
  on public.site_visitors(user_id);

alter table public.site_visitors enable row level security;

-- Visitors are maintained by the trusted backend service role only.
revoke all on public.site_visitors from anon, authenticated;

-- Search indexes. The existing title GIN index is retained; these add the
-- fields actually searched by StreamFlix without requiring a third-party search service.
create index if not exists idx_content_search
  on public.content using gin (
    to_tsvector(
      'english'::regconfig,
      coalesce(title, '') || ' ' || coalesce(description, '') || ' ' || coalesce(synopsis, '') || ' ' || coalesce(director, '') || ' ' || coalesce("cast", '')
    )
  );

create index if not exists idx_favorites_user_content
  on public.favorites(user_id, content_id);

create index if not exists idx_watch_list_user_content
  on public.watch_list(user_id, content_id);

create index if not exists idx_view_history_user_watch_date
  on public.view_history(user_id, watch_date desc);

create index if not exists idx_review_user_content
  on public.review(user_id, content_id);

create or replace function public.get_content_rating_summaries()
returns table(content_id integer, average_rating numeric, review_count bigint)
language sql
stable
security definer
set search_path = public
as $$
  select r.content_id,
         round(avg(r.rating_value), 1) as average_rating,
         count(*)::bigint as review_count
  from public.review r
  group by r.content_id;
$$;

revoke all on function public.get_content_rating_summaries() from public;
grant execute on function public.get_content_rating_summaries() to service_role;

create or replace function public.notify_new_content()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.notifications(user_id, type, title, message)
  select u.user_id, 'content', 'New on StreamFlix', 'A new title is now available: ' || NEW.title
  from public.users u
  where u.deleted_at is null and u.account_status = 'active';
  return NEW;
end;
$$;

drop trigger if exists trg_notify_new_content on public.content;
create trigger trg_notify_new_content
after insert on public.content
for each row execute function public.notify_new_content();

drop policy if exists notifications_auth_owner on public.notifications;
create policy notifications_auth_owner on public.notifications
  for select to authenticated
  using (exists (
    select 1 from public.users u
    where u.user_id = notifications.user_id
      and u.auth_user_id = auth.uid()
      and u.deleted_at is null
  ));

-- Supabase projects normally expose this publication for Realtime. Keep this
-- statement idempotent so environments that already added the table can re-run migrations safely.
do $$
begin
  begin
    alter publication supabase_realtime add table public.notifications;
  exception when duplicate_object then
    null;
  end;
exception when undefined_object then
  null;
end $$;
