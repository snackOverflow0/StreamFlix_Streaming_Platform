alter table public.content
  add column if not exists poster_url text,
  add column if not exists preview_url text,
  add column if not exists hero_url text,
  add column if not exists duration_label varchar(50);

alter table public.merchandise_product
  add column if not exists listing_status varchar(30) not null default 'active',
  add column if not exists image_url text,
  add column if not exists stock_quantity integer not null default 0,
  add column if not exists updated_at timestamptz not null default now();

alter table public.merchandise_transaction
  add column if not exists payment_method varchar(50),
  add column if not exists payment_status varchar(50) not null default 'pending',
  add column if not exists order_status varchar(50) not null default 'pending',
  add column if not exists delivery_method varchar(100),
  add column if not exists delivery_name varchar(150),
  add column if not exists delivery_phone varchar(50),
  add column if not exists delivery_address text,
  add column if not exists payment_reference varchar(255),
  add column if not exists stripe_checkout_session_id varchar(255),
  add column if not exists updated_at timestamptz not null default now();

alter table public.merchandise_transaction
  drop constraint if exists merchandise_transaction_stock_check;

alter table public.merchandise_product
  drop constraint if exists merchandise_product_stock_check;

alter table public.merchandise_product
  add constraint merchandise_product_stock_check check (stock_quantity >= 0);

create index if not exists idx_merch_product_status on public.merchandise_product(listing_status);
create index if not exists idx_merch_tx_user on public.merchandise_transaction(user_id);
create index if not exists idx_merch_tx_status on public.merchandise_transaction(order_status, payment_status);
create unique index if not exists uq_merch_tx_payment_reference on public.merchandise_transaction(payment_reference) where payment_reference is not null;

alter table public.subscriptions
  add column if not exists status varchar(50) not null default 'active',
  add column if not exists stripe_customer_id varchar(255),
  add column if not exists stripe_subscription_id varchar(255),
  add column if not exists stripe_checkout_session_id varchar(255),
  add column if not exists payment_method varchar(50),
  add column if not exists payment_status varchar(50),
  add column if not exists transaction_reference varchar(255),
  add column if not exists paid_at timestamptz,
  add column if not exists updated_at timestamptz not null default now();

create unique index if not exists uq_active_subscription_user on public.subscriptions(subscription_user_id) where status = 'active';
create unique index if not exists uq_stripe_subscription_id on public.subscriptions(stripe_subscription_id) where stripe_subscription_id is not null;

create table if not exists public.payment_transactions (
  payment_transaction_id bigint generated by default as identity primary key,
  user_id integer not null references public.users(user_id) on delete cascade,
  plan_id integer references public.plans(plan_id),
  subscription_id integer references public.subscriptions(subscription_id) on delete set null,
  gateway varchar(30) not null,
  gateway_payment_id varchar(255),
  gateway_session_id varchar(255),
  gateway_subscription_id varchar(255),
  amount numeric(12,2) not null default 0,
  currency varchar(10) not null default 'PHP',
  payment_method varchar(50),
  status varchar(50) not null,
  failure_reason text,
  event_id varchar(255),
  email_sent boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists uq_payment_gateway_event on public.payment_transactions(gateway, event_id) where event_id is not null;
create index if not exists idx_payment_user on public.payment_transactions(user_id, created_at desc);
create index if not exists idx_payment_session on public.payment_transactions(gateway_session_id);

create table if not exists public.email_delivery_log (
  email_delivery_id bigint generated by default as identity primary key,
  user_id integer references public.users(user_id) on delete cascade,
  payment_transaction_id bigint references public.payment_transactions(payment_transaction_id) on delete cascade,
  provider varchar(30) not null,
  recipient_email varchar(255) not null,
  message_type varchar(100) not null,
  status varchar(50) not null,
  provider_message_id varchar(255),
  error_message text,
  created_at timestamptz not null default now()
);

create unique index if not exists uq_email_payment_type on public.email_delivery_log(payment_transaction_id, message_type);

create or replace function public.create_merchandise_order(
  p_delivery_address text,
  p_delivery_method text,
  p_delivery_name text,
  p_delivery_phone text,
  p_payment_method text,
  p_product_id integer,
  p_quantity integer,
  p_user_id integer,
  p_payment_reference text default null,
  p_stripe_checkout_session_id text default null
) returns public.merchandise_transaction
language plpgsql
security definer
set search_path = public
as $$
declare
  v_product public.merchandise_product%rowtype;
  v_total numeric(10,2);
  v_row public.merchandise_transaction;
begin
  if p_quantity is null or p_quantity <= 0 then
    raise exception 'Quantity must be greater than zero';
  end if;

  select * into v_product
  from public.merchandise_product
  where product_id = p_product_id
  for update;

  if not found then
    raise exception 'Product not found';
  end if;

  if coalesce(v_product.listing_status, 'active') <> 'active' then
    raise exception 'Product is not available';
  end if;

  if coalesce(v_product.stock_quantity, 0) < p_quantity then
    raise exception 'Insufficient stock';
  end if;

  update public.merchandise_product
  set stock_quantity = stock_quantity - p_quantity,
      updated_at = now()
  where product_id = p_product_id;

  v_total := round(v_product.price * p_quantity, 2);

  insert into public.merchandise_transaction (
    user_id, product_id, quantity, total_amount,
    payment_method, payment_status, order_status,
    delivery_method, delivery_name, delivery_phone, delivery_address,
    payment_reference, stripe_checkout_session_id
  ) values (
    p_user_id, p_product_id, p_quantity, v_total,
    p_payment_method, case when lower(p_payment_method) = 'cash on delivery' then 'pending' else 'paid' end,
    case when lower(p_payment_method) = 'cash on delivery' then 'pending' else 'processing' end,
    p_delivery_method, p_delivery_name, p_delivery_phone, p_delivery_address,
    p_payment_reference, p_stripe_checkout_session_id
  ) returning * into v_row;

  return v_row;
end;
$$;

revoke all on function public.create_merchandise_order(text,text,text,text,text,integer,integer,integer,text,text) from public;
grant execute on function public.create_merchandise_order(text,text,text,text,text,integer,integer,integer,text,text) to service_role;
